"""Generate native and addon catalogs from the APWorld's authoritative JSON."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from bridge.catalog import Catalog, normalize_reward

KINDS = {"quest": "Quest", "exploration": "Exploration", "boss": "Boss", "dungeon": "Dungeon",
         "level": "Level", "raid": "Raid"}
REWARDS = {"level_cap": "LevelCap", "outland": "Outland", "northrend": "Northrend", "riding": "Riding",
           "talent": "Talent", "ability": "Ability", "vouchers": "Vouchers", "bag": "Bag", "gold": "Gold",
           "consumable": "Consumable", "legendary": "Legendary"}


def mask(values):
    return sum(1 << (value - 1) for value in values)


def quoted(value):
    return json.dumps(value, ensure_ascii=False)


def generate(catalog):
    lines = ["// Generated by tools/build_catalog.py. Edit the JSON catalogs, not this file.", "#pragma once",
             "#include <algorithm>", "#include <array>", "#include <cstdint>", "namespace WoWPilago", "{",
             f"inline constexpr char CatalogVersion[] = {quoted(catalog.version)};",
             "enum class CheckKind : std::uint8_t { Quest, Exploration, Boss, Dungeon, Level, Raid };",
             "enum class RewardKind : std::uint8_t { LevelCap, Outland, Northrend, Riding, Talent, Ability, Vouchers, Bag, Gold, Consumable, Legendary };",
             "struct CheckDef { std::int64_t id; CheckKind kind; std::uint32_t wowId, mapId; std::uint8_t minCap, expansion, riding, faction; std::uint32_t classMask, raceMask; std::array<std::uint32_t,8> bosses; std::uint8_t bossCount; char const* name; };",
             "struct RewardDef { std::int64_t id; RewardKind kind; std::uint32_t value, classMask; char const* name; };",
             "struct RankDef { std::uint32_t spell, baseSpell, classMask; std::uint8_t level; std::uint32_t requiredSpell, requiredSkill, requiredSkillRank; };",
             "struct AbilityDef { std::uint32_t baseSpell; std::uint8_t classId, level; std::array<std::uint32_t,8> prerequisites; std::uint8_t prerequisiteCount; };",
             "struct ProfileDef { std::uint8_t race, playerClass, faction; std::uint32_t zone, map; float x,y,z,o; };",
             "struct GearDef { std::uint32_t entry, classMask, itemSet; std::uint8_t quality, inventoryType, expansion, price; char const* name; };",
             "template<class T, std::size_t N> inline T const* FindById(std::array<T,N> const& rows, std::int64_t id) { auto it=std::find_if(rows.begin(),rows.end(),[id](T const& row){return row.id==id;}); return it==rows.end()?nullptr:&*it; }"]
    checks = catalog.checks
    lines.append(f"inline constexpr std::array<CheckDef,{len(checks)}> Checks = {{{{")
    for check in checks:
        bosses = check.get("boss_ids", [])
        if len(bosses) > 8:
            raise ValueError(f"Too many completion bosses for {check['key']}")
        values = [str(check["ap_id"]), "CheckKind::" + KINDS[check["kind"]], str(check["wow_id"]),
                  str(check.get("map_id", 0)), str(check["min_cap"]),
                  str({"azeroth": 0, "outland": 1, "northrend": 2}[check["expansion"]]),
                  str({"none": 0, "expert": 1, "cold_weather": 2}[check["riding"]]),
                  str({"any": 0, "alliance": 1, "horde": 2}[check["faction"]]),
                  str(mask(check["classes"])), str(mask(check["races"])),
                  "{{" + ",".join(map(str, bosses + [0] * (8 - len(bosses)))) + "}}", str(len(bosses)), quoted(check["name"])]
        lines.append("    {" + ",".join(values) + "},")
    lines.append("}};")
    definitions = []
    for reward in catalog.generic:
        definitions.append((reward, 0))
    for ability in catalog.abilities:
        definitions.append(({"ap_id": ability["ap_id"], "kind": "ability", "value": ability["base_spell"], "name": ability["name"]}, mask([ability["class_id"]])))
    for gear in catalog.gear.values():
        if gear["quality"] == 5:
            definitions.append(({"ap_id": 919400000 + gear["wow_id"], "kind": "legendary", "value": gear["wow_id"], "name": gear["name"]}, mask(gear["allowable_classes"])))
    lines.append(f"inline constexpr std::array<RewardDef,{len(definitions)}> Rewards = {{{{")
    lua = ["-- Generated by tools/build_catalog.py.", "WoWPilagoRewards = {"]
    for reward, classes in sorted(definitions, key=lambda entry: entry[0]["ap_id"]):
        kind, value = normalize_reward(reward)
        lines.append("    {" + f"{reward['ap_id']},RewardKind::{REWARDS[kind]},{value},{classes},{quoted(reward['name'])}" + "},")
        lua.append(f"    [{reward['ap_id']}] = {{name={quoted(reward['name'])},kind={quoted(kind)},value={value}}},")
    lines.append("}};")
    lua.append("}")
    ranks = []
    abilities = []
    for ability in catalog.abilities:
        prerequisites = []
        for requirement in ability["prerequisites"]:
            if requirement["kind"] == "baseline_spells":
                prerequisites.extend(requirement["spell_ids"])
            if requirement["kind"] == "rank_eligibility":
                ranks.append((requirement["spell_id"], ability["base_spell"], mask([ability["class_id"]]),
                              requirement["min_level"], requirement["required_spell"],
                              requirement["required_skill"], requirement["required_skill_rank"]))
        prerequisites = sorted(set(prerequisites))
        if len(prerequisites) > 8:
            raise ValueError("Ability prerequisite table overflow")
        abilities.append((ability, prerequisites))
    lines.append(f"inline constexpr std::array<RankDef,{len(ranks)}> Ranks = {{{{")
    lines.extend("    {" + ",".join(map(str, rank)) + "}," for rank in sorted(ranks))
    lines.append("}};")
    lines.append(f"inline constexpr std::array<AbilityDef,{len(abilities)}> Abilities = {{{{")
    for ability, prerequisites in abilities:
        lines.append("    {" + f"{ability['base_spell']},{ability['class_id']},{ability['min_level']}," +
                     "{{" + ",".join(map(str, prerequisites + [0] * (8 - len(prerequisites)))) + "}}," + str(len(prerequisites)) + "},")
    lines.append("}};")
    lines.append(f"inline constexpr std::array<ProfileDef,{len(catalog.profiles)}> Profiles = {{{{")
    for profile in catalog.profiles:
        coordinates = [f"{float(value):.9f}f" for value in (*profile["position"], profile["orientation"])]
        values = [profile["race_id"], profile["class_id"], 1 if profile["faction"] == "alliance" else 2,
                  profile["starting_zone"], profile["map_id"]]
        lines.append("    {" + ",".join(map(str, values)) + "," + ",".join(coordinates) + "},")
    lines.append("}};")
    lines.append(f"inline constexpr std::array<GearDef,{len(catalog.gear)}> Gear = {{{{")
    for item in sorted(catalog.gear.values(), key=lambda entry: entry["wow_id"]):
        classes = [class_id for class_id in item["allowable_classes"] if item["quality"] == 5
                   or catalog.class_roles[class_id].intersection(item["roles"])]
        values = [item["wow_id"], mask(classes), item["set_id"], item["quality"],
                  item["inventory_type"], item["expansion"], item["price"]]
        lines.append("    {" + ",".join(map(str, values)) + "," + quoted(item["name"]) + "},")
    lines.extend(["}};", "}"])
    return "\n".join(lines) + "\n", "\n".join(lua) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header, lua = generate(Catalog())
    for path, content in ((ROOT / "src" / "APCatalog.h", header), (ROOT / "addon" / "WoWPilago" / "Catalog.lua", lua)):
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated catalog: {path}")
        else:
            path.write_text(content)
    print("PASS native and addon catalogs match the authoritative data")


if __name__ == "__main__":
    main()
