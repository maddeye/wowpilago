#!/usr/bin/env python3
"""Generate, never install, the personal merchant world SQL from SELECT-only pinned DB data."""
import argparse
import csv
import io
import math
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ENTRY = 900500
FIRST_GUID = 9005000
NAME = 'Archipelago Equipment Merchant'
SCRIPT = 'archipelago_merchant'
MARKER = 'WoWPilago merchant v2'
CITIES = (('Stormwind', 0), ('Ironforge', 0), ('Darnassus', 1), ('TheExodar', 530),
          ('Orgrimmar', 1), ('Undercity', 0), ('ThunderBluff', 1), ('SilvermoonCity', 530),
          ('Shattrath', 530), ('Dalaran', 571))
# The Darnassus centre anchor overlaps arena-event pedestals. The temple anchor is inside the same city.
SOURCES = {'Darnassus': 'TempleOfTheMoon'}


def query(sql):
    if not re.match(r'^SELECT\s', sql, re.I) or any(token in sql for token in (';', '--', '/*', '@')):
        raise ValueError('only a single SELECT is permitted')
    password = os.environ.get('WOWPILAGO_DB_PASSWORD')
    if not password:
        raise ValueError('set WOWPILAGO_DB_PASSWORD for the read-only source connection')
    env = dict(os.environ, MYSQL_PWD=password)
    result = subprocess.run(
        ['docker', 'run', '--rm', '--network', 'host', '-e', 'MYSQL_PWD', 'mysql:8.4',
         'mysql', '--protocol=TCP', '-h127.0.0.1', '-P13317', '-uroot', '--batch', '--raw',
         'acore_world', '-e', sql], env=env, check=True, capture_output=True, text=True)
    return list(csv.DictReader(io.StringIO(result.stdout), delimiter='\t'))


def validate_sources(teleports, templates, spawns, nearby):
    """Fail before output on a wrong map, foreign allocation, or overlapping spawn."""
    if any(int(row['entry']) != ENTRY or row['name'] != NAME or row['ScriptName'] != SCRIPT
           for row in templates):
        raise ValueError('entry 900500 belongs to another template')
    for row in spawns:
        guid = int(row['guid'])
        if (not FIRST_GUID <= guid < FIRST_GUID + len(CITIES) or int(row['id']) != ENTRY
                or row['Comment'] != MARKER):
            raise ValueError('reserved spawn range or merchant entry collision')
    points = []
    for city, expected_map in CITIES:
        matches = [row for row in teleports if row['name'] == SOURCES.get(city, city)]
        if len(matches) != 1:
            raise ValueError(f'{city}: expected one game_tele source')
        row = matches[0]
        point = {key: float(row[key]) for key in ('position_x', 'position_y', 'position_z', 'orientation')}
        if int(row['map']) != expected_map or not all(math.isfinite(v) for v in point.values()):
            raise ValueError(f'{city}: wrong map or invalid coordinates')
        if abs(point['position_x']) > 17066 or abs(point['position_y']) > 17066:
            raise ValueError(f'{city}: coordinates outside map bounds')
        for other in nearby:
            if int(other['map']) != expected_map:
                continue
            if int(other['id']) == ENTRY and FIRST_GUID <= int(other['guid']) < FIRST_GUID + len(CITIES):
                continue
            if sum((point[key] - float(other[key])) ** 2
                   for key in ('position_x', 'position_y', 'position_z')) < 9:
                raise ValueError(f'{city}: existing NPC within 3 metres')
        points.append((city, int(row['id']), expected_map, point))
    return points


def generate(teleports, templates, spawns, nearby):
    points = validate_sources(teleports, templates, spawns, nearby)
    sql = ["-- Generated by tools/build_world_sql.py. Source queries are SELECT-only.",
           "-- game_tele coordinates are navigation anchors, not a client walkability test.",
           "-- Reserved entry 900500; spawn GUIDs 9005000..9005009. No foreign rows are deleted.",
           "DROP PROCEDURE IF EXISTS wowpilago_install_merchant_v2;",
           "DELIMITER //", "CREATE PROCEDURE wowpilago_install_merchant_v2()", "BEGIN",
           "  DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;",
           "  START TRANSACTION;",
           f"  IF EXISTS (SELECT 1 FROM creature_template WHERE entry={ENTRY} AND "
           f"(name<>'{NAME}' OR ScriptName<>'{SCRIPT}')) THEN",
           "    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='WoWPilago merchant template collision';", "  END IF;",
           f"  IF EXISTS (SELECT 1 FROM creature WHERE (guid BETWEEN {FIRST_GUID} AND {FIRST_GUID + 9} "
           f"AND (id<>{ENTRY} OR COALESCE(Comment,'')<>'{MARKER}')) OR "
           f"(id={ENTRY} AND (guid NOT BETWEEN {FIRST_GUID} AND {FIRST_GUID + 9} "
           f"OR COALESCE(Comment,'')<>'{MARKER}'))) THEN",
           "    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='WoWPilago merchant spawn collision';", "  END IF;"]
    for city, _, map_id, point in points:
        x, y, z = (point[key] for key in ('position_x', 'position_y', 'position_z'))
        sql.extend([f"  IF EXISTS (SELECT 1 FROM creature WHERE map={map_id} AND "
                    f"NOT (id={ENTRY} AND guid BETWEEN {FIRST_GUID} AND {FIRST_GUID + 9}) AND "
                    f"POW(position_x-({x}),2)+POW(position_y-({y}),2)+POW(position_z-({z}),2)<9) THEN",
                    f"    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='{city}: merchant NPC overlap';", "  END IF;"])
    sql.extend([
        f"  INSERT INTO creature_template (entry,name,minlevel,maxlevel,faction,npcflag,unit_flags,ScriptName) "
        f"VALUES ({ENTRY},'{NAME}',80,80,35,1,2,'{SCRIPT}') "
        "ON DUPLICATE KEY UPDATE name=VALUES(name),faction=35,npcflag=1,unit_flags=2,ScriptName=VALUES(ScriptName);",
        f"  INSERT INTO creature_template_model (CreatureID,Idx,CreatureDisplayID,DisplayScale,Probability) "
        f"VALUES ({ENTRY},0,25465,1,1) ON DUPLICATE KEY UPDATE CreatureDisplayID=25465,DisplayScale=1,Probability=1;"])
    for i, (city, source, map_id, point) in enumerate(points):
        coords = ','.join(format(point[key], '.9g') for key in ('position_x', 'position_y', 'position_z', 'orientation'))
        sql.extend([f"  -- {city}: game_tele.id={source}, map={map_id}",
                    "  INSERT INTO creature (guid,id,map,position_x,position_y,position_z,orientation,spawntimesecs,Comment) "
                    f"VALUES ({FIRST_GUID + i},{ENTRY},{map_id},{coords},120,'{MARKER}') "
                    "ON DUPLICATE KEY UPDATE map=VALUES(map),position_x=VALUES(position_x),"
                    "position_y=VALUES(position_y),position_z=VALUES(position_z),orientation=VALUES(orientation);"])
    sql.extend(["  COMMIT;", "END//", "DELIMITER ;", "CALL wowpilago_install_merchant_v2();",
                "DROP PROCEDURE wowpilago_install_merchant_v2;", ""])
    return '\n'.join(sql)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'sql/world.sql')
    args = parser.parse_args()
    teleports = query('SELECT id,name,map,position_x,position_y,position_z,orientation FROM game_tele WHERE name IN (' +
                      ','.join("'" + SOURCES.get(city, city) + "'" for city, _ in CITIES) + ')')
    templates = query(f'SELECT entry,name,ScriptName FROM creature_template WHERE entry={ENTRY}')
    spawns = query(f'SELECT guid,id,Comment FROM creature WHERE id={ENTRY} OR guid BETWEEN {FIRST_GUID} AND {FIRST_GUID + 9}')
    # Fetch spawn coordinates once, rather than trusting a city label to imply a map or empty location.
    nearby = query('SELECT guid,id,map,position_x,position_y,position_z FROM creature WHERE map IN (0,1,530,571)')
    output = generate(teleports, templates, spawns, nearby)
    args.output.write_text(output)
    print(f'{args.output}: 10 validated game_tele anchors; entry {ENTRY}; no realm writes')


if __name__ == '__main__':
    main()
